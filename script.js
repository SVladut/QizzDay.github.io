let currentCategory = '';
let currentSet = 1;
let currentQuestion = 0;
let score = 0;
let timeLeft;
let timerId;

function createHearts() {
  const heartsContainer = document.getElementById('hearts');
  for (let i = 0; i < 50; i++) {
    const heart = document.createElement('div');
    heart.className = 'heart';
    heart.style.left = Math.random() * 100 + '%';
    heart.style.animationDelay = Math.random() * 2 + 's';
    heart.innerHTML = '❤️';
    heartsContainer.appendChild(heart);
  }
}

function startQuiz(category) {
  const nameField = document.getElementById('participantName').value.trim();
  if (nameField === "") {
    return;
  }
  const setNumber = parseInt(document.getElementById(`${category}Set`).value);
  if (!setNumber || setNumber < 1 || setNumber > 15) {
    return;
  }
  
  if(timerId) clearInterval(timerId);
  
  currentCategory = category;
  currentSet = setNumber;
  currentQuestion = 0;
  score = 0;
  
  document.getElementById('quiz-container').style.display = 'block';
  document.getElementById('timer').style.display = 'block';
  document.getElementById('scoreboard').innerHTML = '';
  
  const totalQuestions = quizzes[currentCategory][currentSet].length;
  timeLeft = totalQuestions * 60;
  document.getElementById('time').textContent = timeLeft;
  
  timerId = setInterval(updateTimer, 1000);
  showQuestion();
}

function updateTimer() {
  timeLeft--;
  document.getElementById('time').textContent = timeLeft;
  
  if(timeLeft <= 0) {
    clearInterval(timerId);
    endQuiz();
  }
}

function showQuestion() {
  const quiz = quizzes[currentCategory][currentSet][currentQuestion];
  document.getElementById('question').innerHTML = `<h3>Întrebarea ${currentQuestion + 1}:</h3>${quiz.question}`;
  const optionsDiv = document.getElementById('options');
  optionsDiv.innerHTML = '';
  quiz.options.forEach((option, index) => {
    const btn = document.createElement('div');
    btn.className = 'option';
    btn.innerHTML = option;
    btn.onclick = () => checkAnswer(index);
    optionsDiv.appendChild(btn);
  });
}

function checkAnswer(selectedIndex) {
  const correctIndex = quizzes[currentCategory][currentSet][currentQuestion].correct;
  if (selectedIndex === correctIndex) {
    score++;
  }
  currentQuestion++;
  if (currentQuestion < quizzes[currentCategory][currentSet].length) {
    showQuestion();
  } else {
    endQuiz();
  }
}

function endQuiz() {
  clearInterval(timerId);
  const total = quizzes[currentCategory][currentSet].length;
  document.getElementById('question').innerHTML = `<h2>Quiz completat! 🎉</h2>`;
  document.getElementById('options').innerHTML = '';
  document.getElementById('scoreboard').innerHTML = `Scor final: ${score} / ${total}`;
  document.getElementById('timer').style.display = 'none';

  let participantName = document.getElementById('participantName').value.trim();
  if (participantName === "") {
    participantName = "Anonim";
  }
  const result = { nume: participantName, rezultat: `${score}` };

  fetch('https://quizzmicro.onrender.com/api/rezultate', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(result)
  })
  .then(response => response.json())
  .then(data => {
    console.log("Rezultat salvat:", data);
  })
  .catch(error => console.error('Eroare la salvare:', error));
}

function showResults() {
  fetch('https://quizzmicro.onrender.com/api/rezultate')
    .then(response => {
      if (!response.ok) {
        throw new Error('Rețea răspuns cu eroare');
      }
      return response.json();
    })
    .then(resultsArray => {
      if (!Array.isArray(resultsArray)) {
        throw new Error('Răspunsul nu este un array');
      }
      let resultsContainer = document.getElementById("results-container");
      if (resultsArray.length === 0) {
        resultsContainer.innerHTML = "<p>Nu există rezultate salvate.</p>";
        return;
      }
      let loc=0;
      let tableHTML = "<table><tr><th>Loc</th><th>Nume</th><th>Rezultat</th></tr>";
      resultsArray.forEach(function(item) {
        loc++;
        tableHTML += `<tr><td>${loc}</td><td>${item.nume}</td><td>${item.rezultat}</td></tr>`;
      });
      tableHTML += "</table>";
      resultsContainer.innerHTML = tableHTML;
    })
    .catch(error => console.error('Eroare la preluarea rezultatelor:', error));
}

